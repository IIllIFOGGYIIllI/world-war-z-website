'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = (name) => fs.readFileSync(name, 'utf8');
const html = read('dashboard.html');
const lazy = read('assets/js/dashboard/lazy-assets.js');
const sw = read('sw.js');
const shell = read('assets/js/dashboard/shell.js');
assert.doesNotMatch(html, /data-nav-label="World Manager"/);
assert.doesNotMatch(html, /data-dashboard-section="world-manager"/);
assert.doesNotMatch(lazy, /ensureWorldManager|WWZWorldManager|world-manager\.js|world-manager\.css|section === 'world-manager'/);
assert.match(html, /data-nav-label="Operations Centre"/);
assert.match(html, /data-dashboard-section="server-audit"/);
assert.match(html, /data-nav-label="Data Management Centre"/);
assert.match(html, /Dual Nasdara separation/);
assert.match(shell, /view === 'staff' && section === 'world-manager' \? 'server-audit'/);
assert.match(shell, /const requestedTarget = sectionTargetFor\(selectedView, requested\.section\);/);
assert.match(shell, /const selectedSection = requestedTarget \? requested\.section : defaultSectionForView\(selectedView\);/);
assert.match(sw, /WWZ_PWA_UPDATE_REVISION = '2026-10-21-dual-nasdara-3-world-manager-retired'/);
assert.match(sw, /APP_CACHE_RELEASE = `\$\{WWZ_PWA_VERSION\}-dual-nasdara-3-world-manager-retired`/);
assert.match(read('assets/js/dashboard/account.js'), /getSelectedServer\?\.\(\)\?\.map_name \|\| 'Nasdara'/);
console.log('PASS: World Manager retired from UI; operational access and PWA updates retained.');

assert(context.includes("world_size: mapKey === 'badlands' ? 16384"));
assert(context.includes("? 'assets/maps/nasdara/preview.jpg?v=wwz-nasdara-1'"));
assert(map.includes("|| null;"), 'Unknown maps must never fall back to Chernarus');
assert(map.includes("satelliteImageUrl: 'assets/maps/nasdara/satellite.webp?v=wwz-nasdara-1'"));
assert(map.includes('if (!config) return null;'));
assert(my.includes("server.map_key === 'badlands' ? Promise.resolve(null)"));

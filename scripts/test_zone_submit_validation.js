'use strict';
const assert = require('node:assert/strict'), fs=require('node:fs');
const zones=fs.readFileSync('assets/js/dashboard/zones.js','utf8');
const html=fs.readFileSync('dashboard.html','utf8');
const lazy=fs.readFileSync('assets/js/dashboard/lazy-assets.js','utf8');
const policy=zones.indexOf('    applyManagedEditorPolicy(zone);');
const shapeAfter=zones.indexOf('    setShapeFields();',policy);
const open=zones.indexOf("    const dialog = $('[data-zone-dialog]');",policy);
assert.ok(policy>=0&&shapeAfter>policy&&shapeAfter<open,'geometry validation must be updated after managed policy');
assert.ok(zones.includes('input.disabled = !circle || state.editorManaged;'),'disable polygon hidden required inputs and managed geometry');
assert.ok(zones.includes("zoneForm?.addEventListener('invalid'"),'show form validation failures');
assert.ok(html.includes('data-zone-save-status=""'),'display status beside Save');
assert.ok(!html.includes('data-zone-undo-point="" type="submit"'),'Undo should never submit');
assert.ok(html.includes('data-zone-undo-point="" type="button"'),'Undo must be button');
assert.ok(html.includes('data-zone-clear-points="" type="button"'),'Clear must be button');
assert.ok(html.includes('data-zone-add-dynamic-list="" type="button"'),'Dynamic List button must not submit');
assert.ok(lazy.includes('zones.js?v=1.59.5&rev=manual-coords-1'),'cache bust for zone editor');
assert.ok(html.includes('lazy-assets.js?v=2.8.1&amp;rev=manual-coords-1'),'cache bust loader');
console.log('PASS: Polygon editor hidden required input and save UI lifecycle');

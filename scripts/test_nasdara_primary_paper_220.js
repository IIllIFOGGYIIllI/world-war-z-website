'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const vmSandbox={window:{},document:{}};
vm.runInNewContext(fs.readFileSync('assets/js/map/wwz-map.js','utf8'),vmSandbox,{filename:'wwz-map.js'});
const map=vmSandbox.window.WWZMap;
const paper=fs.readFileSync('nasdara/index.html','utf8');
const config=map.getConfig('badlands');
assert(config && config.mapMetres===16384 && config.paperUrl.includes('Nasdara_Enhanced_Paper_Map.webp'));
assert(config.roadOrder.length===0 && !config.roadUrl, 'Unverified Nasdara vector network must remain disabled');
assert(!map.getConfig('unknown'), 'Unknown world must never inherit Chernarus');
const grid=config.paperGrid;
const pin=[10490,10623];
const projected=map.worldToLeaflet(pin, 'badlands');
const roundtrip=map.leafletToWorld({lat:projected[0],lng:projected[1]},'badlands');
assert(Math.abs(roundtrip.x-pin[0])<1e-7);
assert(Math.abs(roundtrip.z-pin[1])<1e-7);
const pixelX=grid.originX + pin[0]*grid.pxPerKmX/1000;
const pixelY=grid.yAtZ16000+(16000-pin[1])*grid.pxPerKmY/1000;
assert(pixelX>0 && pixelX<2600 && pixelY>0 && pixelY<2600);
assert(paper.includes('const GRID=Object.freeze({originX:24.63,yAtZ16000:81.2,pxPerKmX:156.05,pxPerKmY:154.75,worldMax:16384})'));
assert(paper.includes('function worldToPaper(x,z)'));
assert(fs.statSync('nasdara/Nasdara_Enhanced_Paper_Map.webp').size > 5e6);
assert(fs.statSync('nasdara/Nasdara_Original_Paper_Map.jpg').size > 2e6);
for(const key of ['chernarus','livonia']) {
  const c=map.getConfig(key);
  assert(c.roadUrl && c.satelliteUrl && c.roadOrder.length>0);
  const middle=c.mapMetres/2;
  const ll=map.worldToLeaflet([middle,middle],key);
  assert(Math.abs(map.leafletToWorld({lat:ll[0],lng:ll[1]},key).x-middle)<1e-7);
}
console.log('Nasdara map projection, approved paper image, original grid and two-world rollback isolation passed');

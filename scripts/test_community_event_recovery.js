'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const page=fs.readFileSync('dashboard.html','utf8');
const app=fs.readFileSync('assets/js/dashboard/community.js','utf8');
const http=fs.readFileSync('assets/js/core/http.js','utf8');
const loader=fs.readFileSync('assets/js/dashboard/lazy-assets.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const readiness=page.indexOf('id="wwz-raid-readiness"');
const analytics=page.indexOf('data-dashboard-section="analytics"');
const planner=page.indexOf('data-dashboard-section="planner"');
assert.ok(readiness>0 && readiness<analytics && analytics<planner,'Raid readiness must be before analytics, not buried in Planner');
assert.equal(page.match(/data-raid-damage-controls hidden/g)?.length,1);
assert.ok(app.includes('const renderRaidPanel = (state = null) =>'));
assert.ok(app.includes('renderRaidPanel(adminPayload?.raid_damage_automation || null);refresh()'),'Controls visible even if workspace API fails');
assert.ok(app.includes("window.addEventListener('wwz:accesschange'"),'Owner permission updates independently');
assert.ok(app.includes('raidToggle.disabled = !live ||'), 'Cannot arm without verified state');
assert.ok(app.includes('const fallbackWindow = window.WWZRaidWeekends?.forServer?.'));
assert.ok(app.includes('await Promise.allSettled(entries.map'), 'Events sections must load independently');
assert.ok(app.includes('window.WWZHttp.request(url,'), 'Authenticated helper used');
assert.ok(app.includes('}, 30_000)'), 'Community request timeout extended');
assert.ok(http.includes("timeoutError.name = 'WWZTimeoutError'"), 'Timeout error actionable');
assert.ok(page.includes('http.js?v=1.41.1&amp;rev=dual-nasdara-auth-1&amp;events=2'));
assert.ok(loader.includes('preflight=1&events=2'));
assert.match(sw, /WWZ_PWA_UPDATE_REVISION = '\d{4}-\d{2}-\d{2}-[a-z0-9-]+';/, 'PWA must use a versioned update token');
console.log('PASS: Events readiness accessible, partial failures isolated, timeout reporting improved');

'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const editor = read('assets/js/dashboard/zones.js');
const page = read('dashboard.html');
const css = read('assets/css/dashboard/zones.css');
const lazy = read('assets/js/dashboard/lazy-assets.js');
const sw = read('sw.js');
assert.ok(editor.includes("[data-zone-save-status]"), 'Save result must remain visible in fixed footer');
assert.ok(editor.includes("const unroutedAlerts = state.zones.filter"), 'Missing Discord destination should be surfaced');
assert.ok(editor.includes("if ($('[data-zone-ping-on-detection]')) $('[data-zone-ping-on-detection]').checked = false;"), 'Radar must be opt-in on new zones');
assert.ok(editor.includes("if ($('[data-zone-alert-enter]')) $('[data-zone-alert-enter]').checked = false;"), 'Entry alert must be opt-in on new zones');
assert.ok(editor.includes("result.notice"), 'Backend warning must be displayed on save');
assert.ok(page.includes('data-zone-save-status=""'), 'Footer status target missing');
assert.ok(!page.includes('checked="" data-zone-ping-on-detection=""'), 'Unsafe radar default in HTML');
assert.ok(!page.includes('checked="" data-zone-alert-enter=""'), 'Unsafe entry alert default in HTML');
assert.ok(css.includes('.zone-save-status[data-kind="error"]'), 'Footer error style missing');
assert.ok(lazy.includes('zones.js?v=1.59.5&rev=manual-coords-1'), 'Updated module not cache-busted');
assert.ok(lazy.includes('zones.css?v=1.59.5&rev=manual-coords-1'), 'Updated stylesheet not cache-busted');
assert.ok(page.includes('lazy-assets.js?v=2.8.4&amp;rev=manual-coords-1&amp;leaderboardfix=1'), 'Updated loader not cache-busted');
assert.match(sw, /WWZ_PWA_UPDATE_REVISION = '\d{4}-\d{2}-\d{2}-[a-z0-9-]+';/, 'PWA refresh token missing');
console.log('Nasdara zone-save frontend checks passed.');
